// ── the tokenizer ──────────────────────────────────────────────────────────

// BERT's basic tokenizer, minus accent stripping: lowercase, split on
// whitespace, then cut punctuation off as its own token.
export function basicTokenize(text) {
  const out = []
  for (const chunk of String(text).toLowerCase().split(/\s+/)) {
    if (!chunk) continue
    let buf = ''
    for (const ch of chunk) {
      if (/[a-z0-9]/.test(ch)) {
        buf += ch
      } else {
        if (buf) out.push(buf)
        buf = ''
        out.push(ch)
      }
    }
    if (buf) out.push(buf)
  }
  return out
}

// Greedy longest-match-first, the WordPiece algorithm itself. Returns [UNK]
// for a word no prefix of which is in the vocabulary.
export function wordpiece(word, vocab) {
  if (!vocab) return null
  if (word.length > 100) return ['[UNK]']
  const pieces = []
  let start = 0
  while (start < word.length) {
    let end = word.length
    let found = null
    while (start < end) {
      const sub = (start === 0 ? '' : '##') + word.slice(start, end)
      if (vocab.has(sub)) {
        found = sub
        break
      }
      end -= 1
    }
    if (found === null) return ['[UNK]']
    pieces.push(found)
    start = end
  }
  return pieces
}

let vocabPromise = null

// One fetch per page, shared by every widget that needs it.
export function loadVocab() {
  if (typeof window === 'undefined') return Promise.resolve(null)
  if (!vocabPromise) {
    vocabPromise = fetch(VOCAB_URL)
      .then((r) => {
        if (!r.ok) throw new Error(`vocab ${r.status}`)
        return r.text()
      })
      .then((t) => new Set(t.split('\n').filter(Boolean)))
      .catch(() => null)
  }
  return vocabPromise
}

