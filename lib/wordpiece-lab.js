// tf_p(d) = sum over words v containing p of count_p(v) * tf_v(d)
export function derivePieces(words, docs) {
  const acc = {}
  for (const w of words) {
    for (const p of new Set(w.pieces)) {
      const count = w.pieces.filter((x) => x === p).length
      acc[p] = acc[p] || {}
      for (const d of docs) acc[p][d] = (acc[p][d] || 0) + count * (w.postings[d] || 0)
    }
  }
  return acc
}

