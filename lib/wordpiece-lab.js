// Tokenize a phrase, preferring the real vocabulary and falling back to the
// table above so the widget still answers for its own presets offline.
export function splitPhrase(text, vocab) {
  return basicTokenize(text).map((w) => ({
    word: w,
    pieces: wordpiece(w, vocab) || KNOWN_SPLITS[w] || null,
  }))
}

