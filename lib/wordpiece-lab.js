export function labChrome(dark) {
  const chrome = chartChrome(dark)
  const vp = vizPalette(dark)
  return {
    ...chrome,
    dark,
    // identity slots, assigned in order: piece, exact word, stem family.
    channel: [vp.series0, vp.series1, vp.series2],
    off: vp.muted,
    // POLARITY, and the only place these widgets spend it: a posting the
    // derivation invents is a failure, not another category.
    bad: vp.bad,
    fill: dark ? 'rgba(255,255,255,0.04)' : '#f2f4f2',
    lane: dark ? 'rgba(255,255,255,0.015)' : '#fbfcfb',
  }
}

