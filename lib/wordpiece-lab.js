// A translucent wash of a role colour, so a tinted chip stays legible in both
// themes without a second hardcoded value per role.
export function hexFade(hex, alpha) {
  const h = hex.replace('#', '')
  const n = parseInt(
    h.length === 3
      ? h
          .split('')
          .map((x) => x + x)
          .join('')
      : h,
    16
  )
  return `rgba(${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}, ${alpha})`
}

